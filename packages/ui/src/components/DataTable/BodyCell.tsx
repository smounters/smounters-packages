import type { CSSProperties, ReactNode } from "react";

const TD = "px-3 py-2 text-sm text-foreground";

/**
 * Ячейка тела таблицы. Узлом dnd-kit НЕ является — и это принципиально.
 *
 * Раньше каждая ячейка вызывала `useSortable({ id: columnId })`, чтобы ехать за своей колонкой во
 * время перетаскивания. Идентификатор при этом был один на всю колонку, то есть под ним
 * регистрировались и заголовок, и все ячейки: на списке в 24 строки и 9 колонок — около двухсот
 * узлов на девять идентификаторов. Перерегистрация при каждой перерисовке не приходила в
 * равновесие, и любое изменение состояния страницы уводило вкладку в петлю: в журнале вебхуков
 * клик по строке подвешивал браузер на секунды, а на списке из одной строки того же экрана всё
 * работало мгновенно.
 *
 * Цена решения: при перетаскивании едет только заголовок, тело перестраивается после отпускания.
 */
export function BodyCell({
  width,
  className,
  children,
}: {
  width?: number | undefined;
  className?: string | undefined;
  children: ReactNode;
}) {
  const style: CSSProperties = { width };
  return (
    <td style={style} className={`${TD} ${className ?? ""}`}>
      {children}
    </td>
  );
}
